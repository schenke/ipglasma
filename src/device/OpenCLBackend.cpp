// The OpenCL backend of the device layer: the kernels of ipg_kernels.h,
// compiled by the OpenCL driver of the device at start-up. It needs
// OpenCL 1.2 only, which is what macOS provides for the GPUs of Apple M
// processors (in single precision: they have no double precision), and
// runs as well on the OpenCL drivers of NVIDIA, AMD and Intel GPUs and on
// CPU implementations such as PoCL (in double precision).
//
// The device is the first GPU found, or else the first device; the
// environment variable IPGLASMA_OPENCL_DEVICE selects another one by its
// number in the list printed with IPGLASMA_OPENCL_DEVICE=list, or by a
// part of its name.

#define CL_TARGET_OPENCL_VERSION 120
#ifndef CL_SILENCE_DEPRECATION
#define CL_SILENCE_DEPRECATION
#endif
#ifdef __APPLE__
#include <OpenCL/opencl.h>
#else
#include <CL/cl.h>
#endif

